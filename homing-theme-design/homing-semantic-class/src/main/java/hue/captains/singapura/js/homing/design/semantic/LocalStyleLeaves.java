package hue.captains.singapura.js.homing.design.semantic;

import hue.captains.singapura.js.homing.component.taxonomy.ComponentBranch;
import hue.captains.singapura.js.homing.component.taxonomy.LocalStyleBranch;
import hue.captains.singapura.js.homing.component.taxonomy.Taxonomy;
import hue.captains.singapura.js.homing.component.taxonomy.VirtualComponent;
import hue.captains.singapura.tao.ontology.StatelessFunctionalObject;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * A local-style branch's leaves as a page has them (RFC 0067, appendix Local Styles): one frozen constant per leaf,
 * generated from the taxonomy as the roles are, by which what the branch styles asks a local style to wear a leaf on
 * an element - never by a string. Each carries its branch, so a local style refuses a leaf of another. One constant
 * for the branch, whichever of its local styles wears it.
 *
 * <pre>{@code
 * const GRID_FRAME = Object.freeze({
 *     CURSOR_BORDER: Object.freeze({ branch: "grid-frame", token: "cursor-border", toString() { return "cursor-border"; } }),
 *     …
 * });
 * }</pre>
 */
public record LocalStyleLeaves() implements StatelessFunctionalObject {

    public static final LocalStyleLeaves INSTANCE = new LocalStyleLeaves();

    /** What the constant is called: the branch's token as a constant's name - {@code GRID_FRAME}. */
    public String name(ComponentBranch branch) { return constant(branch.token()); }

    /** The constant's script: every leaf of the branch, in the taxonomy's order. */
    public List<String> lines(Taxonomy taxonomy, ComponentBranch branch) {
        if (!(branch instanceof LocalStyleBranch))
            throw new IllegalArgumentException(branch.token() + " is no local-style branch: its leaves are worn as components are, by their castings");
        var leaves = new ArrayList<String>();
        for (var n : taxonomy.children(branch))
            if (n instanceof VirtualComponent<?> leaf) leaves.add("    " + constant(leaf.token()) + ": Object.freeze({ branch: " + quoted(branch.token()) + ", token: " + quoted(leaf.token())
                    + ", toString() { return " + quoted(leaf.token()) + "; } })");
        return List.of(
                "// Generated by LocalStyleLeaves from the local-style branch " + branch.token() + " - do not hand-edit.",
                "// Every leaf of the branch, by which what it styles asks a local style to wear it.",
                "const " + name(branch) + " = Object.freeze({\n" + String.join(",\n", leaves) + "\n});");
    }

    private static String constant(String token) { return token.toUpperCase(Locale.ROOT).replace('-', '_'); }

    private static String quoted(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }
}
