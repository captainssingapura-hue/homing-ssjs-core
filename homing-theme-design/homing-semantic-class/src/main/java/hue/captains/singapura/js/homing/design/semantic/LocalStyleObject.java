package hue.captains.singapura.js.homing.design.semantic;

import hue.captains.singapura.js.homing.core.DerivedCss;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.design.Target;
import hue.captains.singapura.js.homing.design.local.ConcreteComponent;
import hue.captains.singapura.tao.ontology.StatelessFunctionalObject;

import java.util.ArrayList;
import java.util.List;

/**
 * A local style as a page has it (RFC 0067, appendix Local Styles): one stateless object, the typed local style,
 * generated as a group of CSS classes is generated into its handles. It carries the branch it styles and its name,
 * and wears and sheds a leaf's classes on an element - every class its concrete leaf wears, one for each target the
 * leaf owns, the same in every style and palette; the local style's sheet says what each draws. What it styles is
 * made with it, asks it to wear a leaf by the leaf's constant ({@link LocalStyleLeaves}), and never touches a class
 * list: the object is its classes' keeper. A leaf of another branch, or one the branch has
 * not, is refused. A leaf that wears an animation effect is switched off and on by its class and its still
 * dual's swapped ({@code still(leaf, el)}, {@code move(leaf, el)}) - nothing more.
 *
 * <p>Generated, it keeps the standard hand-written code keeps: every class is a handle made once by the css
 * manager ({@code css.cls}), and is put on and taken off through it ({@code css.addClass},
 * {@code css.removeClass}) - never through the element's class list. The manager is the page's, injected into
 * the object's module by the sheet it imports - the local style's own sheet, named by what that sheet exports.</p>
 *
 * <pre>{@code
 * void minesweeper_classic_sheet;
 * const MinesweeperClassic = Object.freeze({ branch: "grid-frame", name: "minesweeper-classic", leaves: …,
 *     classes(leaf) { … }, wear(leaf, el) { … }, shed(leaf, el) { … } });
 * }</pre>
 */
public record LocalStyleObject() implements StatelessFunctionalObject {

    public static final LocalStyleObject INSTANCE = new LocalStyleObject();

    /** What the object is called in JavaScript: its local style's type's name - {@code MinesweeperClassic}. */
    public String name(LocalStyleRead read) { return read.localStyle().getClass().getSimpleName(); }

    /**
     * The object's script: a first line that names the local style's sheet, so that it loads wherever the local style
     * is used, then the object.
     *
     * @param sheet the local style's sheet, which exports one constant to be imported by
     */
    public List<String> lines(LocalStyleRead read, DerivedCss<?> sheet) {
        var tokens = SemanticTokens.INSTANCE;
        String name = name(read);
        String branch = read.branch().token();
        String imported = imported(sheet);
        var leaves = new ArrayList<String>();
        var stills = new ArrayList<String>();
        for (ConcreteComponent<?, ?, ?> c : read.concretes()) {
            var classes = new ArrayList<String>();
            for (Target t : read.owns(c.virtual())) {
                String worn = tokens.drawn(read.localStyle(), c.virtual(), t);
                classes.add(handle(worn));
                if (t instanceof Target.Animation)
                    stills.add("        " + quoted(c.virtual().token()) + ": Object.freeze([" + handle(worn) + ", " + handle(tokens.still(worn)) + "])");
            }
            leaves.add("        " + quoted(c.virtual().token()) + ": Object.freeze([" + String.join(", ", classes) + "])");
        }
        return List.of(
                "// Generated by LocalStyleObject from the local style " + read.token() + " of " + branch + " - do not hand-edit.",
                "void " + imported + ";   // the local style's sheet: imported with it, so that it loads wherever the local style is used",
                "const " + name + " = Object.freeze({",
                "    branch: " + quoted(branch) + ",",
                "    name: " + quoted(read.token()) + ",",
                "    // every class each leaf's concrete leaf wears, as the css manager's handle: one for each target the leaf owns",
                "    leaves: Object.freeze({",
                String.join(",\n", leaves),
                "    }),",
                "    // a leaf's classes; refused for a leaf of another branch, or one this branch has not",
                "    classes(leaf) {",
                "        if (!leaf || leaf.branch !== " + quoted(branch) + ")",
                "            throw new Error(\"[" + name + "] a leaf of " + branch + " is asked, not \" + (leaf && leaf.token));",
                "        var classes = " + name + ".leaves[leaf.token];",
                "        if (!classes) throw new Error(\"[" + name + "] " + branch + " has no leaf '\" + leaf.token + \"'\");",
                "        return classes;",
                "    },",
                "    // the leaves that wear an animation effect: the effect's class and its still dual's, as handles - swapped, the effect is off",
                "    stills: Object.freeze({",
                String.join(",\n", stills),
                "    }),",
                "    wear(leaf, el) { " + name + ".classes(leaf).forEach(function (c) { css.addClass(el, c); }); return el; },",
                "    shed(leaf, el) {",
                "        " + name + ".classes(leaf).forEach(function (c) { css.removeClass(el, c); });",
                "        var s = " + name + ".stills[leaf.token]; if (s) css.removeClass(el, s[1]);",
                "        return el;",
                "    },",
                "    // a leaf's effect switched off: its class swapped for its still dual's - the effect without any motion",
                "    still(leaf, el) { var s = " + name + "._stills(leaf); css.removeClass(el, s[0]); css.addClass(el, s[1]); return el; },",
                "    // and on again",
                "    move(leaf, el) { var s = " + name + "._stills(leaf); css.removeClass(el, s[1]); css.addClass(el, s[0]); return el; },",
                "    _stills(leaf) {",
                "        " + name + ".classes(leaf);",
                "        var s = " + name + ".stills[leaf.token];",
                "        if (!s) throw new Error(\"[" + name + "] '\" + leaf.token + \"' wears no animation effect\");",
                "        return s;",
                "    },",
                "    toString() { return " + quoted(read.token()) + "; }",
                "});");
    }

    /** The name a sheet is imported by: the one constant it exports. */
    private static String imported(DerivedCss<?> sheet) {
        List<? extends Exportable<?>> exports = sheet.exports().exports();
        if (exports.size() != 1 || !(exports.get(0) instanceof Exportable._Constant<?>))
            throw new IllegalArgumentException(sheet.getClass().getSimpleName() + " exports " + exports.size()
                    + " things: a local style's sheet exports one constant, which its object imports so that it loads");
        return exports.get(0).getClass().getSimpleName();
    }

    private static String quoted(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }

    /** A class's handle, made once by the css manager, as a generated group of CSS classes makes its own. */
    private static String handle(String className) { return "css.cls(" + quoted(className) + ")"; }
}
