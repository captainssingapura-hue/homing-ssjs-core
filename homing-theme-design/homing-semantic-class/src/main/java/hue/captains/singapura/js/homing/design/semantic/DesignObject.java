package hue.captains.singapura.js.homing.design.semantic;

import hue.captains.singapura.js.homing.component.taxonomy.ConcreteComponent;
import hue.captains.singapura.js.homing.design.Target;
import hue.captains.singapura.tao.ontology.StatelessFunctionalObject;

import java.util.ArrayList;
import java.util.List;

/**
 * A design as a page has it (RFC 0067, appendix Virtual Leaves and Designs): one stateless object, the typed
 * design, generated as a group of CSS classes is generated into its handles. It carries the branch it designs
 * and its name, and wears and sheds a leaf's classes on an element - every class its concrete leaf wears, one
 * for each target the leaf owns, the same in every theme; the theme's sheet says what each draws. What it
 * designs is made with it, asks it to wear a leaf by the leaf's constant ({@link DesignLeaves}), and never
 * touches a class list: the object is its classes' manager. A leaf of another branch, or one the branch has
 * not, is refused.
 *
 * <pre>{@code
 * void minesweeper_classic_sheet;
 * const MinesweeperClassic = Object.freeze({ branch: "grid-frame", name: "minesweeper-classic", leaves: …,
 *     classes(leaf) { … }, wear(leaf, el) { … }, shed(leaf, el) { … } });
 * }</pre>
 */
public record DesignObject() implements StatelessFunctionalObject {

    public static final DesignObject INSTANCE = new DesignObject();

    /** What the object is called in JavaScript: its design's type's name - {@code MinesweeperClassic}. */
    public String name(DesignRead design) { return design.design().getClass().getSimpleName(); }

    /**
     * The object's script: a first line that names the design's sheet, so that it loads wherever the design
     * is used, then the object.
     *
     * @param sheet the name the design's sheet is imported by
     */
    public List<String> lines(DesignRead design, String sheet) {
        var tokens = SemanticTokens.INSTANCE;
        String name = name(design);
        String branch = design.branch().token();
        var leaves = new ArrayList<String>();
        for (ConcreteComponent<?, ?, ?> c : design.concretes()) {
            var classes = new ArrayList<String>();
            for (Target t : ReadDesigns.owned(c.virtual())) classes.add(quoted(tokens.drawn(design.design(), c.virtual(), t)));
            leaves.add("        " + quoted(c.virtual().token()) + ": Object.freeze([" + String.join(", ", classes) + "])");
        }
        return List.of(
                "// Generated by DesignObject from the design " + design.token() + " of " + branch + " - do not hand-edit.",
                "void " + sheet + ";   // the design's sheet: imported with the design, so that it loads wherever the design is used",
                "const " + name + " = Object.freeze({",
                "    branch: " + quoted(branch) + ",",
                "    name: " + quoted(design.token()) + ",",
                "    // every class each leaf's concrete leaf wears: one for each target the leaf owns",
                "    leaves: Object.freeze({",
                String.join(",\n", leaves),
                "    }),",
                "    // a leaf's classes; refused for a leaf of another branch, or one this branch has not",
                "    classes(leaf) {",
                "        if (!leaf || leaf.branch !== " + quoted(branch) + ")",
                "            throw new Error(\"[" + name + "] a leaf of " + branch + " is asked, not \" + (leaf && leaf.token));",
                "        var classes = " + name + ".leaves[leaf.token];",
                "        if (!classes) throw new Error(\"[" + name + "] " + branch + " has no leaf '\" + leaf.token + \"'\");",
                "        return classes;",
                "    },",
                "    wear(leaf, el) { " + name + ".classes(leaf).forEach(function (c) { el.classList.add(c); }); return el; },",
                "    shed(leaf, el) { " + name + ".classes(leaf).forEach(function (c) { el.classList.remove(c); }); return el; },",
                "    toString() { return " + quoted(design.token()) + "; }",
                "});");
    }

    private static String quoted(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }
}
