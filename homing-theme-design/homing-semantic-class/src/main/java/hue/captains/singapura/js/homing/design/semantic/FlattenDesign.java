package hue.captains.singapura.js.homing.design.semantic;

import hue.captains.singapura.js.homing.component.taxonomy.ConcreteComponent;
import hue.captains.singapura.js.homing.component.taxonomy.VirtualComponent;
import hue.captains.singapura.js.homing.design.Extent;
import hue.captains.singapura.js.homing.design.Growth;
import hue.captains.singapura.js.homing.design.State;
import hue.captains.singapura.js.homing.design.Target;
import hue.captains.singapura.tao.ontology.StatelessFunctionalObject;
import hue.captains.singapura.tao.ontology.ValueObject;

import java.util.ArrayList;
import java.util.Map;

/**
 * A design's sheet in a theme, flattened (RFC 0067, appendix Virtual Leaves and Designs): one rule for every
 * class its concrete leaves wear - a concrete leaf on a target its leaf owns, under {@code
 * .design___leaf__target} - the body its drawing says, its states nested within in the cascade's order, so a
 * state's body outweighs the look while the state holds and of two states the later wins. A drawing taken from
 * another concrete leaf is copied, saying where it came from; a drawing of nothing has no rule. A sheet of its
 * own, beside the house's look sheet, which it never touches. Given a design {@link ReadDesigns} has read.
 */
public record FlattenDesign() implements StatelessFunctionalObject {

    public static final FlattenDesign INSTANCE = new FlattenDesign();

    /** The sheet, how many rules it holds, and how many of them were taken from another concrete leaf. */
    public record Flattened(String css, int drawn, int copied) implements ValueObject {}

    public Flattened flatten(DesignRead design, Dressed theme, String title) {
        var tokens = SemanticTokens.INSTANCE;
        var css = new StringBuilder();
        int drawn = 0, copied = 0;
        css.append("/* ").append(title).append(" - a design flattened: every class its concrete leaves wear, a target each, its states within.\n")
           .append("   Generated by FlattenDesign; do not edit. */\n");
        // the degrees a body may read, and the colours CSS has no property for, as the look sheet declares them
        css.append(Extent.PROPERTY).append('\n');
        for (Growth g : Growth.values()) css.append(g.property()).append('\n');
        for (Target t : tokens.leaves()) for (String r : t.registrations()) css.append(r).append('\n');
        css.append('\n');

        for (ConcreteComponent<?, ?, ?> c : design.concretes()) {
            VirtualComponent<?> leaf = c.virtual();
            for (Target t : ReadDesigns.owned(leaf)) {
                ResolveDrawing.Resolved r = ResolveDrawing.INSTANCE.resolve(c, t, theme);
                if (!(r.drawing() instanceof Drawing.Own<?> own)) continue;
                var parts = new ArrayList<String>();
                Map<State, String> bodies = own.answer().bodies();
                for (State s : State.values()) {
                    String body = bodies.get(s);
                    if (body == null || body.isBlank()) continue;
                    String drawnBody = drawnOn(t, normal(body));
                    parts.add(s == State.REST ? drawnBody : s.selector() + " {\n" + indent(drawnBody) + "\n}");
                }
                if (parts.isEmpty()) continue;
                boolean taken = r.by() != c;
                if (taken) css.append("/* from ").append(tokens.drawn(r.by().design(), leaf, t)).append(" */\n");
                css.append('.').append(tokens.drawn(design.design(), leaf, t)).append(" {\n").append(indent(String.join("\n", parts))).append("\n}\n");
                drawn++;
                if (taken) copied++;
            }
        }
        return new Flattened(css.toString(), drawn, copied);
    }

    /** A body where its target draws: on the element, or nested on the pseudo-element the target paints on. */
    private static String drawnOn(Target t, String body) {
        return t.pseudo() == null ? body : "&" + t.pseudo() + " {\n" + indent(body) + "\n}";
    }

    /** A body as written, each line its own, without the indent it was written at. */
    private static String normal(String body) {
        return String.join("\n", body.strip().lines().map(String::strip).filter(l -> !l.isEmpty()).toList());
    }

    private static String indent(String text) {
        return String.join("\n", text.lines().map(l -> "    " + l).toList());
    }
}
