package hue.captains.singapura.js.homing.design.semantic;

import hue.captains.singapura.js.homing.component.taxonomy.VirtualComponent;
import hue.captains.singapura.js.homing.design.AnimationEffect;
import hue.captains.singapura.js.homing.design.Extent;
import hue.captains.singapura.js.homing.design.Growth;
import hue.captains.singapura.js.homing.design.State;
import hue.captains.singapura.js.homing.design.Target;
import hue.captains.singapura.js.homing.design.color.ColorScheme;
import hue.captains.singapura.js.homing.design.local.ConcreteComponent;
import hue.captains.singapura.tao.ontology.StatelessFunctionalObject;
import hue.captains.singapura.tao.ontology.Scalar;

import java.util.ArrayList;
import java.util.Map;
import java.util.Objects;

/**
 * A local style's sheet in a style, flattened (RFC 0067, appendix Local Styles): one rule for every class its concrete
 * leaves wear - a concrete leaf on a target its leaf owns, under {@code .local-style___leaf__target} - the body its
 * drawing says, its states nested within in the cascade's order, so a state's body outweighs the look while the state
 * holds and of two states the later wins. A drawing taken from another concrete leaf is copied, saying where it came
 * from; a drawing of nothing has no rule. An animation drawn with an effect is the effect's class, its still dual's
 * class beside it ({@code .local-style___leaf__animation-effect-still}), and the effect's keyframes, written once at the
 * head of the sheet ({@link Effects}).
 *
 * <p>One sheet for each style, the same in every palette: a palettable colour is written as its palette's variable,
 * which the palette's sheet defines, so a switch of palette repaints it and only a switch of style fetches it again
 * (appendix Two Classes per Leaf). A sheet of its own, beside the style's, which it never touches. Given a local style
 * {@link ReadLocalStyles} has read.</p>
 */
public record FlattenLocalStyle() implements StatelessFunctionalObject {

    public static final FlattenLocalStyle INSTANCE = new FlattenLocalStyle();

    /** The sheet, how many rules it holds, and how many were taken from another concrete leaf. */
    public record Flattened(String css, int drawn, int copied) implements Scalar {}

    /** One target's rule: its text, whether it was taken from another concrete leaf, and the effect it wears or null. */
    private record Rule(String css, boolean taken, AnimationEffect effect) {}

    /**
     * Flattens the local style for {@code style}, with {@code title} at the head of the sheet; refuses a style whose
     * scheme does not see the local style's.
     */
    public Flattened flatten(LocalStyleRead read, InStyle style, String title) {
        ColorScheme mine = Schemes.INSTANCE.of(read.localStyle()).orElse(null), wears = Schemes.INSTANCE.of(style.style()).orElse(null);
        if (mine == null || wears == null || !Schemes.INSTANCE.sees(wears, mine))
            throw new IllegalArgumentException(read.token() + " is drawn only in a style whose scheme sees its own, and "
                    + style.style().token() + "'s does not (D33)");
        var rules = new ArrayList<Rule>();
        for (ConcreteComponent<?, ?, ?> c : read.concretes())
            for (Target t : read.owns(c.virtual())) {
                Rule rule = rule(read, c, t, style);
                if (rule != null) rules.add(rule);
            }
        var css = new StringBuilder(head(title));
        // the keyframes of every effect the local style wears that moves, once, ahead of the classes that run them
        String keyframes = Effects.INSTANCE.keyframes(rules.stream().map(Rule::effect).filter(Objects::nonNull).toList());
        if (!keyframes.isEmpty()) css.append(keyframes).append("\n\n");
        rules.forEach(r -> css.append(r.css()));
        return new Flattened(css.toString(), rules.size(), (int) rules.stream().filter(Rule::taken).count());
    }

    /** The sheet's head: what it is, the degrees a body may read, and the colours CSS has no property for, as the style's sheet declares them. */
    private String head(String title) {
        var css = new StringBuilder();
        css.append("/* ").append(title).append(" - a local style flattened: every class its concrete leaves wear, a target each, its states within;\n")
           .append("   its palettable colours the palette's variables. Generated by FlattenLocalStyle; do not edit. */\n");
        css.append(Extent.PROPERTY).append('\n');
        for (Growth g : Growth.values()) css.append(g.property()).append('\n');
        for (Target t : SemanticTokens.INSTANCE.leaves()) for (String r : t.registrations()) css.append(r).append('\n');
        return css.append('\n').toString();
    }

    /** A concrete leaf's rule on a target: an effect's class with its still dual beside it, or the bodies drawn; null when nothing is drawn. */
    private Rule rule(LocalStyleRead read, ConcreteComponent<?, ?, ?> c, Target t, InStyle style) {
        var tokens = SemanticTokens.INSTANCE;
        VirtualComponent<?> leaf = c.virtual();
        ResolveDrawing.Resolved r = ResolveDrawing.INSTANCE.resolve(read.taxonomy(), c, t, style);
        boolean taken = r.by() != c;
        String from = taken ? "/* from " + tokens.drawn(r.by().localStyle(), leaf, t) + " */\n" : "";
        String worn = tokens.drawn(read.localStyle(), leaf, t);
        if (r.effect() != null) {
            String moving = "/* " + r.effect().token() + " */\n." + worn + " {\n" + indent(Effects.INSTANCE.moving(r.effect())) + "\n}\n";
            String still = "." + tokens.still(worn) + " {\n" + indent(Effects.INSTANCE.still(r.effect())) + "\n}\n";
            return new Rule(from + moving + still, taken, r.effect());
        }
        var parts = new ArrayList<String>();
        Map<State, String> bodies = r.bodies();
        for (State s : State.values()) {
            String body = bodies.get(s);
            if (body == null || body.isBlank()) continue;
            String drawnBody = drawnOn(t, normal(body));
            parts.add(s == State.REST ? drawnBody : s.selector() + " {\n" + indent(drawnBody) + "\n}");
        }
        if (parts.isEmpty()) return null;
        return new Rule(from + "." + worn + " {\n" + indent(String.join("\n", parts)) + "\n}\n", taken, null);
    }

    /** A body where its target draws: on the element, or nested on the pseudo-element the target paints on. */
    private String drawnOn(Target t, String body) {
        return t.pseudo() == null ? body : "&" + t.pseudo() + " {\n" + indent(body) + "\n}";
    }

    /** A body as written, each line its own, without the indent it was written at. */
    private String normal(String body) {
        return String.join("\n", body.strip().lines().map(String::strip).filter(l -> !l.isEmpty()).toList());
    }

    private String indent(String text) {
        return String.join("\n", text.lines().map(l -> "    " + l).toList());
    }
}
