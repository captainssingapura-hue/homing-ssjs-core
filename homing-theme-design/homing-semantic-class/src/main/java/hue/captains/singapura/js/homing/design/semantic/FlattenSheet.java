package hue.captains.singapura.js.homing.design.semantic;

import hue.captains.singapura.js.homing.component.taxonomy.Casting;
import hue.captains.singapura.js.homing.component.taxonomy.Component;
import hue.captains.singapura.js.homing.component.taxonomy.Taxonomy;
import hue.captains.singapura.js.homing.design.Carrier;
import hue.captains.singapura.js.homing.design.Extent;
import hue.captains.singapura.js.homing.design.Growth;
import hue.captains.singapura.js.homing.design.State;
import hue.captains.singapura.js.homing.design.Target;
import hue.captains.singapura.tao.ontology.StatelessFunctionalObject;
import hue.captains.singapura.tao.ontology.ValueObject;

import java.util.ArrayList;
import java.util.List;

/**
 * A theme's sheet, flattened: one rule for every class an element can wear, its body copied from
 * the node that answers it. Resolution is atomic - one node for a node, a state and a target - so
 * flattening is a copy and never a merge: the body moves to the worn class's selector unchanged.
 *
 * <ul>
 *   <li><b>Looks</b>, first: every casting the taxonomy has, on every CSS target, each the answering
 *       look's body under {@code .casting__target}.</li>
 *   <li><b>Treatments</b>, after, a state at a time in the cascade's order: every component, in
 *       every state its target offers that some component up its lineage answers, the body nested on
 *       the state's selector under {@code .component__target--state} - so a treatment outweighs the
 *       look while its state holds, and of two treatments the later state wins, as the old sheets
 *       had it.</li>
 * </ul>
 *
 * A silence is copied as nothing. A look nothing answers, the root included, has no rule: it is
 * reported, and the sheet is incomplete. Each rule says where its body came from - the layer and
 * the class - unless the worn style or the palette answered the class itself.
 */
public record FlattenSheet() implements StatelessFunctionalObject {

    public static final FlattenSheet INSTANCE = new FlattenSheet();

    /** The sheet, what is in it, and every look nothing answers. */
    public record Flattened(String css, int looks, int treatments, int copied, List<String> unanswered) implements ValueObject {
        public Flattened { unanswered = List.copyOf(unanswered); }
    }

    public Flattened flatten(Taxonomy taxonomy, Dressed theme, String title) {
        var tokens = SemanticTokens.INSTANCE;
        var resolver = ResolveSemanticClass.INSTANCE;
        var targets = tokens.cssLeaves();
        var css = new StringBuilder();
        var unanswered = new ArrayList<String>();
        int looks = 0, treatments = 0, copied = 0;
        css.append("/* ").append(title).append(" - flattened: every class an element can wear, its body copied from the node that answers it.\n")
           .append("   Generated by FlattenSheet; do not edit. */\n");
        // the degrees a body may read: numbers the element sets on itself, never inherited
        css.append(Extent.PROPERTY).append('\n');
        for (Growth g : Growth.values()) css.append(g.property()).append('\n');
        // the colours CSS has no property for - a shadow's, a gradient's: set on the element by its own colour class
        for (Target t : tokens.leaves()) for (String r : t.registrations()) css.append(r).append('\n');

        css.append("\n/* ── looks ── */\n");
        for (Casting c : taxonomy.castings())
            for (Target t : targets) {
                Resolution r = resolver.resolve(taxonomy, theme, c, State.REST, t);
                if (!(r.outcome() instanceof Resolution.Answered a)) {
                    unanswered.add(tokens.look(c, t));
                    continue;
                }
                if (a.body().isBlank()) continue;
                css.append(rule(tokens.look(c, t), a, own(t, theme), normal(a.body())));
                looks++;
                if (!a.node().equals(c)) copied++;
            }

        for (State s : State.values()) {
            if (s == State.REST) continue;
            var block = new StringBuilder();
            for (Component<?> leaf : taxonomy.components())
                for (Target t : targets) {
                    if (!t.states().contains(s)) continue;
                    Casting c = new Casting(leaf);
                    Resolution r = resolver.resolve(taxonomy, theme, c, s, t);
                    if (!(r.outcome() instanceof Resolution.Answered a)) continue;
                    if (a.body().isBlank()) continue;
                    block.append(rule(tokens.treatment(c, s, t), a, own(t, theme), s.selector() + " {\n" + indent(normal(a.body())) + "\n}"));
                    treatments++;
                    if (!a.node().equals(c)) copied++;
                }
            if (!block.isEmpty()) css.append("\n/* ── ").append(tokens.state(s)).append(" ── */\n").append(block);
        }
        return new Flattened(css.toString(), looks, treatments, copied, unanswered);
    }

    /** A rule for the class worn, saying where its body came from unless the identity worn answered it itself. */
    private static String rule(String worn, Resolution.Answered from, String own, String body) {
        boolean itself = worn.equals(from.className()) && own.equals(from.layer());
        return (itself ? "" : "/* from " + from.layer() + ": " + from.className() + " */\n") + "." + worn + " {\n" + indent(body) + "\n}\n";
    }

    /** The identity asked first for a target: the palette for colour, the worn style for the rest. */
    private static String own(Target t, Dressed theme) {
        return t instanceof Target.Color ? theme.palette().token() : theme.style().token();
    }

    /** A body as written, each line its own, without the indent it was written at. */
    private static String normal(String body) {
        return String.join("\n", body.strip().lines().map(String::strip).filter(l -> !l.isEmpty()).toList());
    }

    private static String indent(String text) {
        return String.join("\n", text.lines().map(l -> "    " + l).toList());
    }
}
