package hue.captains.singapura.js.homing.design.styling;

import hue.captains.singapura.js.homing.design.color.Palettable;
import hue.captains.singapura.js.homing.design.semantic.ColorPalette;
import hue.captains.singapura.js.homing.design.semantic.ColorTree;
import hue.captains.singapura.tao.ontology.StatelessFunctionalObject;
import hue.captains.singapura.tao.ontology.ValueObject;

import java.util.ArrayList;
import java.util.List;

/**
 * A palette written out as a sheet (RFC 0067, appendix Two Classes per Leaf): on {@code :root}, one {@code --fp-}
 * variable for every palettable colour the palette's scheme sees, each worked out when the sheet is made through the two
 * layers - the palette and the extension's sub-palette for it, then the palettes below it and the extension's last
 * word - and saying who gave it wherever the palette did not itself. Fixed and interpolated colours are none of a
 * palette's: they are assigned in the CSS that uses them.
 *
 * <p>Refused when the palette is no chain down the schemes or leaves a colour unanswered, with every problem at once: a
 * palette's sheet is complete, so a style's {@code var(--fp-...)} never falls back. Every palette of one scheme defines
 * the same variables, so a style's CSS is the same in each, and changing the palette changes this sheet alone.</p>
 */
public record PaletteSheet() implements StatelessFunctionalObject {

    public static final PaletteSheet INSTANCE = new PaletteSheet();

    /**
     * A palette's sheet, and the variables it defines.
     *
     * @param css       the sheet
     * @param variables the variables defined, in the tree's order: {@code --fp-page}
     */
    public record Written(String css, List<String> variables) implements ValueObject {
        public Written { variables = List.copyOf(variables); }
    }

    public Written write(ColorTree tree, ColorPalette<?> palette) {
        List<String> problems = tree.check(palette);
        if (!problems.isEmpty())
            throw new IllegalArgumentException(palette.token() + "'s sheet cannot be written: " + String.join("; ", problems));
        var css = new StringBuilder();
        css.append("/* ").append(palette.token()).append(" - every palettable colour its scheme sees, from palette (--fp-).\n")
           .append("   Generated by PaletteSheet; do not edit. */\n:root {\n");
        var variables = new ArrayList<String>();
        for (Palettable<?, ?> p : tree.palettables(palette)) {
            ColorTree.Resolved r = tree.resolution(palette, p).orElseThrow();
            String variable = ColorVariables.INSTANCE.of(p);
            variables.add(variable);
            css.append("    ").append(variable).append(": ").append(r.color().css()).append(';');
            if (!r.from().isEmpty()) css.append("   /* ").append(r.from()).append(" */");
            css.append('\n');
        }
        css.append("}\n");
        return new Written(css.toString(), variables);
    }
}
