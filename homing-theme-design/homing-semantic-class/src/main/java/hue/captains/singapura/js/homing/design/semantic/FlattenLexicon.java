package hue.captains.singapura.js.homing.design.semantic;

import hue.captains.singapura.js.homing.component.taxonomy.Lexicon;
import hue.captains.singapura.js.homing.component.taxonomy.Word;
import hue.captains.singapura.js.homing.design.Target;
import hue.captains.singapura.tao.ontology.StatelessFunctionalObject;
import hue.captains.singapura.tao.ontology.ValueObject;

import java.util.ArrayList;
import java.util.List;

/**
 * A lexicon's sheet for a style, flattened: one rule for every word, the glyph the style worn writes
 * for it ({@link WriteWord}) drawn where a mark draws its picture - {@code .word-close::before}. A mark
 * shows a word by wearing its class ({@link SemanticTokens#word}); the rule draws nothing else, so the
 * mark keeps the ink it stands on and the box its owner gives it. Each rule says where its glyph came
 * from unless the worn style wrote it itself. A word nothing writes has no rule: it is reported, and
 * the sheet is incomplete.
 */
public record FlattenLexicon() implements StatelessFunctionalObject {

    public static final FlattenLexicon INSTANCE = new FlattenLexicon();

    /** The sheet, how many words it writes, how many of them a style below the worn one wrote, and every word nothing writes. */
    public record Flattened(String css, int written, int copied, List<String> unwritten) implements ValueObject {
        public Flattened { unwritten = List.copyOf(unwritten); }
    }

    public Flattened flatten(Lexicon lexicon, DesignStyle<?> style, String title) {
        var write = WriteWord.INSTANCE;
        var chain = write.chain(style);
        var writings = chain.stream().map(write::writings).toList();
        var css = new StringBuilder();
        var unwritten = new ArrayList<String>();
        int written = 0, copied = 0;
        css.append("/* ").append(title).append(" - the lexicon written: every word a mark may show, the glyph its style draws for it.\n")
           .append("   Generated by FlattenLexicon; do not edit. */\n");
        for (Word<?> word : lexicon.words()) {
            DesignStyle<?> by = null;
            String glyph = null;
            for (int i = 0; i < chain.size() && by == null; i++)
                for (Writing w : writings.get(i))
                    if (w.word().equals(word)) { by = chain.get(i); glyph = w.glyph(); break; }
            if (by == null) {
                unwritten.add(word.token());
                continue;
            }
            css.append(by == style ? "" : "/* from " + by.token() + " */\n")
               .append('.').append(SemanticTokens.INSTANCE.word(word)).append(Target.Type.Glyph.INSTANCE.pseudo())
               .append(" {\n    content: \"").append(escaped(glyph)).append("\";\n}\n");
            written++;
            if (by != style) copied++;
        }
        return new Flattened(css.toString(), written, copied, unwritten);
    }

    /** A glyph as a CSS string holds it: a quote and a backslash escaped. */
    private static String escaped(String glyph) {
        return glyph.replace("\\", "\\\\").replace("\"", "\\\"");
    }
}
